-- PeoplePulse optional Snowflake adapter.
-- Run as a security administrator, then an account administrator where noted.
-- Replace placeholder administrator roles to match your organization.

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS PEOPLEPULSE_READER;
CREATE ROLE IF NOT EXISTS PEOPLEPULSE_ANALYST;
CREATE ROLE IF NOT EXISTS PEOPLEPULSE_TRANSFORMER;
CREATE ROLE IF NOT EXISTS PEOPLEPULSE_LOADER;
CREATE ROLE IF NOT EXISTS PEOPLEPULSE_SECURITY_ADMIN;

GRANT ROLE PEOPLEPULSE_READER TO ROLE PEOPLEPULSE_ANALYST;
GRANT ROLE PEOPLEPULSE_READER TO ROLE PEOPLEPULSE_TRANSFORMER;
GRANT ROLE PEOPLEPULSE_READER TO ROLE PEOPLEPULSE_LOADER;

USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS PEOPLEPULSE_MONTHLY_MONITOR
    WITH CREDIT_QUOTA = 100
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 75 PERCENT DO NOTIFY
        ON 90 PERCENT DO SUSPEND
        ON 100 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS PEOPLEPULSE_LOADING
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    RESOURCE_MONITOR = PEOPLEPULSE_MONTHLY_MONITOR
    COMMENT = 'Short-lived ingestion warehouse; query tag is required by clients';

CREATE WAREHOUSE IF NOT EXISTS PEOPLEPULSE_TRANSFORMING
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    MAX_CLUSTER_COUNT = 2
    MIN_CLUSTER_COUNT = 1
    SCALING_POLICY = ECONOMY
    RESOURCE_MONITOR = PEOPLEPULSE_MONTHLY_MONITOR;

CREATE WAREHOUSE IF NOT EXISTS PEOPLEPULSE_REPORTING
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 120
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    RESOURCE_MONITOR = PEOPLEPULSE_MONTHLY_MONITOR;

CREATE DATABASE IF NOT EXISTS PEOPLEPULSE
    DATA_RETENTION_TIME_IN_DAYS = 7
    COMMENT = 'Synthetic people analytics data only';

CREATE SCHEMA IF NOT EXISTS PEOPLEPULSE.RAW;
CREATE SCHEMA IF NOT EXISTS PEOPLEPULSE.STAGING;
CREATE SCHEMA IF NOT EXISTS PEOPLEPULSE.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS PEOPLEPULSE.CORE;
CREATE SCHEMA IF NOT EXISTS PEOPLEPULSE.MARTS;
CREATE SCHEMA IF NOT EXISTS PEOPLEPULSE.GOVERNANCE;
CREATE SCHEMA IF NOT EXISTS PEOPLEPULSE.AUDIT;

USE ROLE SECURITYADMIN;

GRANT USAGE ON DATABASE PEOPLEPULSE TO ROLE PEOPLEPULSE_READER;
GRANT USAGE ON SCHEMA PEOPLEPULSE.MARTS TO ROLE PEOPLEPULSE_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA PEOPLEPULSE.MARTS TO ROLE PEOPLEPULSE_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PEOPLEPULSE.MARTS TO ROLE PEOPLEPULSE_READER;
GRANT USAGE ON WAREHOUSE PEOPLEPULSE_REPORTING TO ROLE PEOPLEPULSE_READER;

GRANT USAGE ON DATABASE PEOPLEPULSE TO ROLE PEOPLEPULSE_LOADER;
GRANT USAGE ON SCHEMA PEOPLEPULSE.RAW TO ROLE PEOPLEPULSE_LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT
    ON SCHEMA PEOPLEPULSE.RAW TO ROLE PEOPLEPULSE_LOADER;
GRANT USAGE ON WAREHOUSE PEOPLEPULSE_LOADING TO ROLE PEOPLEPULSE_LOADER;

GRANT USAGE ON DATABASE PEOPLEPULSE TO ROLE PEOPLEPULSE_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PEOPLEPULSE TO ROLE PEOPLEPULSE_TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW, CREATE DYNAMIC TABLE
    ON ALL SCHEMAS IN DATABASE PEOPLEPULSE TO ROLE PEOPLEPULSE_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE PEOPLEPULSE TO ROLE PEOPLEPULSE_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE PEOPLEPULSE TO ROLE PEOPLEPULSE_TRANSFORMER;
GRANT USAGE ON WAREHOUSE PEOPLEPULSE_TRANSFORMING TO ROLE PEOPLEPULSE_TRANSFORMER;

USE ROLE ACCOUNTADMIN;
USE SCHEMA PEOPLEPULSE.GOVERNANCE;

CREATE TAG IF NOT EXISTS DATA_CLASSIFICATION
    ALLOWED_VALUES 'public', 'internal', 'confidential', 'restricted_pii';

CREATE MASKING POLICY IF NOT EXISTS MASK_EMAIL AS (value STRING)
RETURNS STRING ->
    CASE
        WHEN IS_ROLE_IN_SESSION('PEOPLEPULSE_SECURITY_ADMIN') THEN value
        ELSE CONCAT('***@', SPLIT_PART(value, '@', 2))
    END;

CREATE MASKING POLICY IF NOT EXISTS MASK_TEXT AS (value STRING)
RETURNS STRING ->
    CASE
        WHEN IS_ROLE_IN_SESSION('PEOPLEPULSE_SECURITY_ADMIN') THEN value
        ELSE '***'
    END;

CREATE MASKING POLICY IF NOT EXISTS MASK_DATE AS (value DATE)
RETURNS DATE ->
    CASE
        WHEN IS_ROLE_IN_SESSION('PEOPLEPULSE_SECURITY_ADMIN') THEN value
        ELSE DATE_FROM_PARTS(YEAR(value), 1, 1)
    END;

